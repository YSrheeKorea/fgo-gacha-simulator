// Official FGO Servant Coin grant on Summon
window.getFgoSummonCoins = function(sv) {
  if (!sv) return 0;
  const r = sv.rarity;
  if (r === 5) return 90;
  if (r === 4) return (sv.limited || sv.storyLocked) ? 50 : 30;
  if (r === 3) return (sv.limited || sv.storyLocked) ? 30 : 15;
  if (r === 2) return 6;
  if (r === 1) return sv.limited ? 15 : 2;
  if (r === 0) return 50; // ★0 앙리마유
  return 15;
};

// Official FGO Servant Coin grant on Bond Level Up (to target bondLv)
// Lv.1~6: +5, Lv.7~9: +20, Lv.10: +40, Lv.11: +50, Lv.12~15: +60 (Total 420 at Bond 15; Lv.16 = 0)
window.getFgoBondCoins = function(targetBondLv) {
  if (targetBondLv >= 1 && targetBondLv <= 6) return 5;
  if (targetBondLv >= 7 && targetBondLv <= 9) return 20;
  if (targetBondLv === 10) return 40;
  if (targetBondLv === 11) return 50;
  if (targetBondLv >= 12 && targetBondLv <= 15) return 60;
  return 0;
};

// Official FGO Palingenesis step rules
window.getFgoGrailStep = function(curCap) {
  if (curCap >= 120) return null;
  if (curCap < 90) {
    const nextCap = Math.min(90, curCap + 5);
    return { nextCap, grails: 1, coins: 0, qp: 2000000 };
  }
  if (curCap < 100) {
    return { nextCap: curCap + 2, grails: 1, coins: 0, qp: 5000000 };
  }
  // Lv.100 -> 120: +2 Lv per Grail + 30 Servant Coins + 15M QP
  return { nextCap: curCap + 2, grails: 1, coins: 30, qp: 15000000 };
};

